import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const port=process.env.APP_PORT || '8080';
const browser=await chromium.launch({headless:true,args:['--no-proxy-server','--host-resolver-rules=MAP angebote-http.test 127.0.0.1']});
try {
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.route('https://fonts.gstatic.com/**',route=>route.abort());
  await page.route('https://cdn.marktguru.de/**',route=>route.abort());
  await page.goto(`http://angebote-http.test:${port}/`,{waitUntil:'domcontentloaded'});
  await page.getByText('Neuronales Produktnetz',{exact:true}).click();
  await page.getByText('gespeichert · v2',{exact:true}).waitFor();
  const active=(await page.getByTestId('active-text-model').innerText()).match(/product-v2-[a-f0-9]+/)[0];
  await page.locator('#training-key').fill('wrong-key');
  await page.getByRole('button',{name:'Letzte Ablehnung prüfen',exact:true}).click();
  await page.getByRole('alert').waitFor();
  await page.locator('#training-key').fill(process.env.TRAINING_ADMIN_TOKEN || '');
  await page.getByRole('button',{name:'Letzte Ablehnung prüfen',exact:true}).click();
  await page.getByTestId('review-target').getByText(/Prüfung des abgelehnten Kandidaten/).waitFor();
  await page.getByTestId('control-diagnostics').getByText('Fehler auf dem Kontrollsatz',{exact:true}).waitFor();
  await page.getByTestId('control-diagnostics').getByText(/Erwartet: passt; Kandidat: passt nicht/).first().waitFor();
  assert.equal(await page.getByTestId('control-diagnostics').getByRole('button').count(),0,'Control examples are read-only');
  await page.getByText(/Konflikt aus dem gespeicherten Kandidatenbericht/).waitFor();
  await page.getByText('Produkt: Tafeläpfel XXL',{exact:true}).waitFor();
  assert.equal((await page.getByTestId('active-text-model').innerText()).match(/product-v2-[a-f0-9]+/)[0],active);
  await page.getByTestId('review-card').getByRole('button',{name:'Passt',exact:true}).click();
  await page.getByText('Alle verfügbaren Konflikte sind geprüft. Starten Sie jetzt ein neues Training.',{exact:true}).waitFor();
  await page.getByText('Geprüfte Beispiele in der Datenbank: 3.',{exact:true}).waitFor();
  await page.reload();
  await page.getByText('Neuronales Produktnetz',{exact:true}).click();
  await page.locator('#training-key').fill(process.env.TRAINING_ADMIN_TOKEN || '');
  await page.getByRole('button',{name:'Letzte Ablehnung prüfen',exact:true}).click();
  await page.getByText('Alle verfügbaren Konflikte sind geprüft. Starten Sie jetzt ein neues Training.',{exact:true}).waitFor();
  assert.equal((await page.getByTestId('active-text-model').innerText()).match(/product-v2-[a-f0-9]+/)[0],active);
  assert.deepEqual(errors,[]);
  console.log('Rejected-candidate browser review passed: owner auth, stored conflict, persisted correction, active model unchanged');
}finally{await browser.close();}
